import express from 'express';
import path from 'path';
import fs from 'fs';
import { fileURLToPath, pathToFileURL } from 'url';
import dotenv from 'dotenv';

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const app = express();
const PORT = process.env.PORT || 3000;

// Trust reverse proxy (Nginx / Cloudflare / Apache)
app.set('trust proxy', 1);

// Canonical Host (non-www) & Trailing Slash Redirection (SEO consistency)
app.use((req, res, next) => {
  if (req.method !== 'GET' && req.method !== 'HEAD') {
    return next();
  }

  const host = (req.headers.host || '').trim();
  const isWww = /^www\./i.test(host);

  const urlParts = (req.originalUrl || req.url).split('?');
  const pathname = urlParts[0];
  const search = urlParts[1] ? `?${urlParts[1]}` : '';
  const hasTrailingSlash = pathname.length > 1 && pathname.endsWith('/');

  // Skip API routes and assets
  if (pathname.startsWith('/api/') || pathname.startsWith('/assets/')) {
    return next();
  }

  if (isWww || hasTrailingSlash) {
    const targetHost = isWww ? host.replace(/^www\./i, '') : host;
    const targetPath = hasTrailingSlash ? pathname.replace(/\/+$/, '') : pathname;
    const protocol = req.protocol === 'https' || req.headers['x-forwarded-proto'] === 'https' ? 'https' : 'http';
    const targetUrl = `${protocol}://${targetHost}${targetPath}${search}`;
    return res.redirect(301, targetUrl);
  }

  next();
});

// Stripe webhook requires raw Buffer for cryptographic signature verification
app.post(['/api/stripe-webhook', '/api/stripe/webhook'], express.raw({ type: '*/*', limit: '2mb' }), async (req, res) => {
  try {
    req.rawBody = req.body;
    const { default: handler } = await import('./api/stripe-webhook.js');
    await handler(req, res);
  } catch (error) {
    console.error('[stripe-webhook error]', error);
    if (!res.headersSent) res.status(500).json({ error: error.message });
  }
});

// JSON body parser for all other /api endpoints (max 10MB to accommodate base64 payment receipts)
app.use('/api', express.json({
  limit: '10mb',
  verify: (req, res, buf) => {
    req.rawBody = buf;
  },
}));

// Known API rewrites (matching vercel.json)
const API_REWRITES = {
  'stripe/webhook': 'stripe-webhook',
  'verify-stripe-payment': 'order-status',
  'capture-paypal-order': 'order-status',
};

// Universal API request handler (compatible with Express v4 and Express v5)
app.use('/api', async (req, res, next) => {
  let endpoint = (req.originalUrl || req.url || req.path)
    .split('?')[0]
    .replace(/^\/api\//, '')
    .replace(/\/$/, '');
  if (API_REWRITES[endpoint]) {
    endpoint = API_REWRITES[endpoint];
  }

  const filePath = path.resolve(__dirname, `api/${endpoint}.js`);
  if (!fs.existsSync(filePath)) {
    return res.status(404).json({ error: `API endpoint '/api/${endpoint}' not found` });
  }

  try {
    const { default: handler } = await import(`./api/${endpoint}.js`);
    if (typeof handler === 'function') {
      await handler(req, res);
    } else {
      res.status(500).json({ error: 'Handler is not callable' });
    }
  } catch (error) {
    console.error(`[API error: /api/${endpoint}]`, error);
    if (!res.headersSent) {
      res.status(500).json({ error: error.message || 'Internal server error' });
    }
  }
});

// Dynamic Sitemap for search engine crawlers (Google, Bing, etc.)
app.get('/sitemap.xml', async (req, res) => {
  try {
    const { generateDynamicSitemap, getBaseUrl } = await import('./api/_seo-renderer.js');
    const baseUrl = getBaseUrl(req);
    const xml = await generateDynamicSitemap(baseUrl);
    res.setHeader('Content-Type', 'application/xml; charset=utf-8');
    res.setHeader('Cache-Control', 'public, max-age=600, s-maxage=3600');
    res.send(xml);
  } catch (error) {
    console.error('[sitemap error]', error);
    res.status(500).send('<?xml version="1.0" encoding="UTF-8"?><urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"></urlset>');
  }
});

// Dynamic Robots.txt
app.get('/robots.txt', async (req, res) => {
  try {
    const { generateDynamicRobots, getBaseUrl } = await import('./api/_seo-renderer.js');
    const baseUrl = getBaseUrl(req);
    const robots = generateDynamicRobots(baseUrl);
    res.setHeader('Content-Type', 'text/plain; charset=utf-8');
    res.setHeader('Cache-Control', 'public, max-age=86400');
    res.send(robots);
  } catch (error) {
    console.error('[robots error]', error);
    res.status(500).send('User-agent: *\nAllow: /\n');
  }
});

// Serve frontend static files from dist/ (generated by `npm run build`)
const distPath = path.resolve(__dirname, 'dist');
if (fs.existsSync(distPath)) {
  app.use(express.static(distPath, {
    maxAge: '1d',
    index: false,
    redirect: false,
    setHeaders: (res, filePath) => {
      // Immutable caching for Vite hashed assets
      if (filePath.includes(`${path.sep}assets${path.sep}`)) {
        res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
      }
    },
  }));
}

// In-memory HTML cache for fast SEO injection
let cachedIndexHtml = null;
let lastIndexMtime = 0;

// Standalone Legal Pages (Privacy Policy & Terms of Service for Google OAuth verification)
app.get(['/privacy', '/privacy/'], (req, res, next) => {
  const privacyPath = path.resolve(distPath, 'privacy/index.html');
  const fallbackPath = path.resolve(__dirname, 'public/privacy/index.html');
  if (fs.existsSync(privacyPath)) {
    return res.sendFile(privacyPath);
  }
  if (fs.existsSync(fallbackPath)) {
    return res.sendFile(fallbackPath);
  }
  next();
});

app.get(['/terms', '/terms/'], (req, res, next) => {
  const termsPath = path.resolve(distPath, 'terms/index.html');
  const fallbackPath = path.resolve(__dirname, 'public/terms/index.html');
  if (fs.existsSync(termsPath)) {
    return res.sendFile(termsPath);
  }
  if (fs.existsSync(fallbackPath)) {
    return res.sendFile(fallbackPath);
  }
  next();
});

// SPA fallback: any non-API GET route serves index.html with dynamic SEO metadata injection
app.use(async (req, res) => {
  if (req.method !== 'GET') {
    return res.status(404).json({ error: 'Not found' });
  }
  const indexPath = path.resolve(distPath, 'index.html');
  if (fs.existsSync(indexPath)) {
    try {
      const stats = fs.statSync(indexPath);
      if (!cachedIndexHtml || stats.mtimeMs > lastIndexMtime) {
        cachedIndexHtml = fs.readFileSync(indexPath, 'utf-8');
        lastIndexMtime = stats.mtimeMs;
      }

      const { injectSeoTags, getBaseUrl } = await import('./api/_seo-renderer.js');
      const baseUrl = getBaseUrl(req);
      const seoResult = await injectSeoTags(cachedIndexHtml, req.originalUrl || req.url, baseUrl);
      const status = (seoResult && seoResult.status) || 200;
      const renderedHtml = seoResult && typeof seoResult.html === 'string' ? seoResult.html : String(seoResult);

      res.status(status);
      res.setHeader('Content-Type', 'text/html; charset=utf-8');
      res.send(renderedHtml);
    } catch (err) {
      console.error('[SSR-SEO fallback error]', err);
      res.sendFile(indexPath);
    }
  } else {
    res.status(503).send(`
      <!DOCTYPE html>
      <html>
        <head><title>Build Required</title></head>
        <body style="font-family: sans-serif; text-align: center; padding: 50px;">
          <h2>Application build not found</h2>
          <p>Please run <code>npm run build</code> to compile the frontend assets before starting the server.</p>
        </body>
      </html>
    `);
  }
});

// Determine if server.js is running as the main process (directly via Node or managed by PM2)
const isMain =
  !process.env.NODE_TEST_CONTEXT &&
  process.env.NODE_ENV !== 'test' &&
  (
    process.env.pm_id !== undefined ||
    process.env.pm_exec_path !== undefined ||
    !process.argv[1] ||
    process.argv[1].endsWith('server.js') ||
    process.argv[1].includes('pm2') ||
    process.argv[1].includes('ProcessContainer') ||
    (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href)
  );

if (isMain) {
  app.listen(PORT, () => {
    console.log(`\n======================================================`);
    console.log(` DVDs Zone Production Server running on port ${PORT}`);
    console.log(` Base site URL: ${process.env.SITE_URL || `http://localhost:${PORT}`}`);
    console.log(`======================================================\n`);
  });
}

export { app };
export default app;
