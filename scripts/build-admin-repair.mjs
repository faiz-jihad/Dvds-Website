import { readFile, writeFile } from 'node:fs/promises';

// Repair the existing operational schema without replaying catalogue imports or seeds.
const migrations = [
  '20260914000006_company_identity.sql',
  '20260914000008_payment_system_upgrade.sql',
  '20260915000001_admin_reliability.sql',
  '20260915000002_checkout_sync.sql',
  '20260916000001_admin_feature_integrity.sql',
  '20260916000002_global_checkout.sql',
];
const header = `-- Generated by node scripts/build-admin-repair.mjs. Do not edit by hand.
-- Run in the connected project's Supabase SQL Editor using the postgres role.
-- Repairs payment columns and administrator RPCs on an existing operational database.
-- No products, users or orders are deleted. Run the whole file as one transaction.
BEGIN;
DO $$
BEGIN
  IF to_regclass('public.profiles') IS NULL
     OR to_regclass('public.orders') IS NULL
     OR to_regclass('public.order_items') IS NULL
     OR to_regclass('public.store_settings') IS NULL
     OR to_regclass('public.admin_audit_log') IS NULL
     OR to_regclass('public.order_status_history') IS NULL
     OR to_regprocedure('public.is_admin()') IS NULL
     OR to_regprocedure('public.reserve_order_inventory(uuid)') IS NULL
     OR to_regprocedure('public.release_order_inventory(uuid)') IS NULL THEN
    RAISE EXCEPTION 'Base operational schema is missing. Apply the earlier migrations before this repair.';
  END IF;
END;
$$;
`;
const sections = await Promise.all(migrations.map(async (file) => {
  let sql = await readFile(new URL(`../supabase/migrations/${file}`, import.meta.url), 'utf8');
  // Add missing legal columns without resetting an existing company's settings.
  if (file === '20260914000006_company_identity.sql') {
    sql = sql.replace(/UPDATE public\.store_settings[\s\S]*?updated_at = NOW\(\);/, '-- Preserve existing company identity values.');
  }
  // The migration is run once normally; the repair must also be safe to repeat.
  sql = sql.replace('CREATE POLICY "Staff can read payment events"', 'DROP POLICY IF EXISTS "Staff can read payment events" ON public.payment_events;\nCREATE POLICY "Staff can read payment events"');
  return `\n-- Source: ${file}\n${sql.trim()}\n`;
}));
await writeFile(new URL('../supabase/repair_admin_schema.sql', import.meta.url), `${header}${sections.join('')}\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n`);
console.log('Generated supabase/repair_admin_schema.sql');
